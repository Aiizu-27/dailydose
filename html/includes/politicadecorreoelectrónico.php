# Política de Envío de Correos de DAILY DOSE

DAILY DOSE envía únicamente correos electrónicos relacionados con la cuenta del usuario, como:

- Confirmación de registro y verificación de cuenta
- Recuperación de contraseña mediante enlace seguro
- Notificaciones importantes sobre la actividad de la cuenta

No se enviarán correos publicitarios sin el consentimiento explícito del usuario.

Todos los correos se envían a usuarios que se han registrado voluntariamente. Los usuarios pueden darse de baja o eliminar su cuenta en cualquier momento contactando con el administrador del servicio.